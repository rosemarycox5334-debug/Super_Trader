import { createHash } from 'node:crypto';
import { dirname, join, resolve, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const PACKAGE_ROOT = fileURLToPath(new URL('../', import.meta.url));
const SOURCE_ROOT = resolve(PACKAGE_ROOT, '..');
export const RUNTIME_FILES = Object.freeze({
  backend: ['__init__.py', 'agent.py', 'app.py', 'db.py', 'experts.py', 'jobs.py', 'journal.py', 'market.py', 'memory.py', 'model_gateway.py', 'plugins.py', 'quant.py', 'research.py', 'selection.py', 'seeds.py', 'serve.py', 'services.py', 'settings.py', 'watchlist.py'],
  'backend/factors': ['__init__.py', 'dataset.py', 'targets.py', 'dsl.py', 'evaluate.py', 'seed_pool.py', 'sandbox.py', 'service.py', 'cli.py', 'batch.py', 'research.py'],
  super_trader: ['__init__.py', '__main__.py', 'accuracy.py', 'accuracy_ranking.py', 'accuracy_report.py', 'cli.py', 'config.py', 'crosssection.py', 'crosssection_report.py', 'data.py', 'diagnose.py', 'evaluate.py', 'features.py', 'fullfit.py', 'fullfit_report.py', 'fullfit_table.py', 'personal_report.py', 'personalize.py', 'predict.py', 'report.py', 'rules.py', 'scan.py', 'stats.py', 'universe.py'],
});
export const REQUIREMENTS = 'numpy>=2.0\npandas>=2.2\npyarrow>=15.0\nscipy>=1.11\nfastapi>=0.110\nuvicorn>=0.27\nhttpx>=0.27\n';

/** Deterministic, explicit source allowlist. Never copies data, keys, DBs or tests. */
export async function buildRuntime({ sourceRoot = SOURCE_ROOT, outputRoot = join(PACKAGE_ROOT, 'runtime') } = {}) {
  sourceRoot = resolve(sourceRoot); outputRoot = resolve(outputRoot);
  if (sourceRoot === outputRoot || !relative(sourceRoot, outputRoot)) throw new Error('Runtime output must differ from source root');
  const files = ['LICENSE', 'requirements.txt', ...Object.entries(RUNTIME_FILES).flatMap(([pkg, names]) => names.map(name => `${pkg}/${name}`))].sort();
  const allowed = new Set(files.concat('manifest.json'));
  const allowedDirs = new Set();
  for (const file of files) {
    for (let dir = dirname(file); dir && dir !== '.'; dir = dirname(dir)) allowedDirs.add(dir.replaceAll('\\', '/'));
  }
  // Refuse unexpected payloads; only generated bytecode is safe to discard.
  async function inspect(directory) {
    for (const entry of await readdir(directory, { withFileTypes: true }).catch(error => { if (error.code === 'ENOENT') return []; throw error; })) {
      const path = join(directory, entry.name);
      const rel = relative(outputRoot, path).replaceAll('\\', '/');
      if (entry.isSymbolicLink()) throw new Error(`Runtime output contains symlink: ${rel}`);
      if (entry.isDirectory()) {
        if (entry.name === '__pycache__') await rm(path, { recursive: true });
        else if (allowedDirs.has(rel)) await inspect(path);
        else throw new Error(`Unexpected runtime directory: ${rel}`);
      } else if (!allowed.has(rel)) throw new Error(`Unexpected runtime file: ${rel}`);
    }
  }
  await inspect(outputRoot);
  const manifest = { format: 1, files: {} };
  for (const name of files) {
    const target = join(outputRoot, name);
    await mkdir(dirname(target), { recursive: true });
    if (name === 'requirements.txt') await writeFile(target, REQUIREMENTS);
    else await copyFile(join(sourceRoot, name), target);
    manifest.files[name] = createHash('sha256').update(await readFile(target)).digest('hex');
  }
  await writeFile(join(outputRoot, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  return { outputRoot, files: files.length, manifest };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const result = await buildRuntime();
  console.log(`Bundled runtime: ${result.files} allowlisted files; no Python installation or data download performed.`);
}
